// Generates src/generated/registry.ts: static imports of every content JSON file,
// so both Next.js and the future Expo app can bundle content without `fs`.
import { readdirSync, existsSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const LOCALES = ["en", "fr", "nl", "th"];
const lines = ["// AUTO-GENERATED by scripts/generate-registry.mjs. Do not edit.", "/* eslint-disable */"];
let n = 0;
const imp = (rel) => {
  const id = `m${n++}`;
  lines.push(`import ${id} from "../../${rel}";`);
  return id;
};
const dirs = (d) =>
  existsSync(join(root, d))
    ? readdirSync(join(root, d), { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort()
    : [];

function collection(dir, metaFile) {
  const out = [];
  for (const slug of dirs(dir)) {
    const base = `${dir}/${slug}`;
    if (!existsSync(join(root, base, metaFile))) continue;
    const meta = imp(`${base}/${metaFile}`);
    const locs = LOCALES.filter((l) => existsSync(join(root, base, `${l}.json`))).map(
      (l) => `${l}: ${imp(`${base}/${l}.json`)}`,
    );
    out.push(`  ${JSON.stringify(slug)}: { meta: ${meta}, text: { ${locs.join(", ")} } },`);
  }
  return out;
}

const visas = collection("visas", "facts.json");
const guides = collection("guides", "meta.json");
const pages = collection("pages", "meta.json");
const msgs = LOCALES.filter((l) => existsSync(join(root, "messages", `${l}.json`))).map(
  (l) => `${l}: ${imp(`messages/${l}.json`)}`,
);
const single = (f) => (existsSync(join(root, f)) ? imp(f) : "null");
const countries = single("countries.json");
const images = single("images.json");
const announcements = single("announcements.json");

lines.push(
  "",
  "type Entry = { meta: unknown; text: Partial<Record<string, unknown>> };",
  `export const visaFiles: Record<string, Entry> = {\n${visas.join("\n")}\n};`,
  `export const guideFiles: Record<string, Entry> = {\n${guides.join("\n")}\n};`,
  `export const pageFiles: Record<string, Entry> = {\n${pages.join("\n")}\n};`,
  `export const messageFiles: Partial<Record<string, unknown>> = { ${msgs.join(", ")} };`,
  `export const countriesFile: unknown = ${countries};`,
  `export const imagesFile: unknown = ${images};`,
  `export const announcementsFile: unknown = ${announcements};`,
  "",
);
mkdirSync(join(root, "src/generated"), { recursive: true });
writeFileSync(join(root, "src/generated/registry.ts"), lines.join("\n"));
console.log(`registry: ${visas.length} visas, ${guides.length} guides, ${pages.length} pages`);
